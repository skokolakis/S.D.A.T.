def descriptive_stats(self, columns: List[str]) -> pd.DataFrame:
        """Calculate basic statistics, using geometric stats for logarithmic data."""
        stats_dict = {}
        for col in columns:
            if col in self.data.columns:
                # Clean the data: drop NaNs and infinite values which break calculations
                values = self.data[col].replace([np.inf, -np.inf], np.nan).dropna()
                
                if len(values) == 0:
                    continue
                
                is_phase = 'phase' in col.lower()
                is_strictly_positive = (values > 0).all()
                
                # If it's Magnitude, Resistance, or Resistivity (strictly positive)
                if is_strictly_positive and not is_phase:
                    log_vals = np.log10(values)
                    stats_dict[col] = {
                        'Count': len(values),
                        'Type': 'Logarithmic',
                        'Mean (Geom)': 10**(log_vals.mean()),
                        'Std Dev (Geom Factor)': 10**(log_vals.std()),
                        'Min': values.min(),
                        'Max': values.max(),
                        'Q1': values.quantile(0.25),
                        'Median': values.median(),
                        'Q3': values.quantile(0.75),
                    }
                else:
                    # Linear stats for Phase or data with negatives/zeroes
                    stats_dict[col] = {
                        'Count': len(values),
                        'Type': 'Linear',
                        'Mean (Arith)': values.mean(),
                        'Std Dev (Arith)': values.std(),
                        'Min': values.min(),
                        'Max': values.max(),
                        'Q1': values.quantile(0.25),
                        'Median': values.median(),
                        'Q3': values.quantile(0.75),
                    }
        
        # Fill missing keys with NaN so the dataframe columns align perfectly
        return pd.DataFrame(stats_dict).T
    

def get_loop_selection_ui(datasets: Dict[str, pd.DataFrame], key_prefix: str) -> Optional[Dict[str, List[str]]]:
    """Loop filter per file. Returns {file: selected loops}, or None when no file has loops."""
    with_loops = {name: df for name, df in datasets.items() if 'Loop' in df.columns}
    if not with_loops:
        return None
    selected_loops = {}
    for name, df in with_loops.items():
        loops = sorted(df['Loop'].unique())
        label = "Loops" if len(datasets) == 1 else f"Loops · {name}"
        selected_loops[name] = st.multiselect(
            label, options=loops, default=loops, key=f"{key_prefix}_loops_{name}",
            help="Repeated frequency sweeps within one file. Loops that overlap indicate a stable, "
                 "reproducible measurement."
        )
    return selected_loops


